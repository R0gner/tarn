#!/usr/bin/env node
// tarn · icons: manage Lucide symbols (ISC) at a fixed version. Node ≥ 22, no npm packages.
//
//   node tools/icons.mjs add <lucide-name> [--as <kit-name>]   fetch the symbol at the fixed version, register it, rebuild
//   node tools/icons.mjs build                                  regenerate icons/SOURCES.md and js/icons-data.js (offline)
//   node tools/icons.mjs check                                  check that both match icons/*.svg (exit 1 otherwise)
//   node tools/icons.mjs list
//
// Source: https://github.com/lucide-icons/lucide (tag LUCIDE_VERSION). Only the used SVGs are in the repo
// (icons/<lucide-name>.svg, unmodified); the mapping kit name → Lucide name is in icons/manifest.json,
// js/icons-data.js is generated from it (at runtime only this file is loaded; no build in the browser, no innerHTML).
// The network is used only by `add`.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

export const LUCIDE_VERSION = '1.70.0';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'icons');
const MANIFEST = path.join(DIR, 'manifest.json');
const RAW = (name, file = `icons/${name}.svg`) => `https://raw.githubusercontent.com/lucide-icons/lucide/${LUCIDE_VERSION}/${file}`;
const TAGS = new Set(['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);
const ATTRS = new Set(['d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'x1', 'y1', 'x2', 'y2', 'width', 'height', 'points']);
const sha = (buf) => crypto.createHash('sha256').update(buf).digest('hex');

const readManifest = () => (fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, 'utf8')) : { version: LUCIDE_VERSION, icons: {} });

/** SVG text → element list [[tag, {attr}], …] (allowed elements and attributes only; otherwise an error). */
export function parseSvg(text, name = '?') {
  const out = [];
  const body = text.replace(/<!--[\s\S]*?-->/g, '');
  const inner = /<svg\b[^>]*>([\s\S]*)<\/svg>/.exec(body);
  if (!inner) throw new Error(`${name}: no <svg>`);
  for (const m of inner[1].matchAll(/<\s*([a-zA-Z]+)\b([^>]*?)\/?>/g)) {
    const tag = m[1].toLowerCase();
    if (!TAGS.has(tag)) throw new Error(`${name}: element <${tag}> not supported`);
    const attrs = {};
    for (const a of m[2].matchAll(/([a-zA-Z][\w-]*)\s*=\s*"([^"]*)"/g)) {
      if (!ATTRS.has(a[1])) throw new Error(`${name}: attribute ${a[1]} not supported`);
      attrs[a[1]] = a[2];
    }
    out.push([tag, attrs]);
  }
  if (!out.length) throw new Error(`${name}: no shapes`);
  return out;
}

/** Generated files as { 'js/icons-data.js': text, 'icons/SOURCES.md': text } (pure, for build and check). */
export function generate(manifest = readManifest()) {
  const entries = Object.entries(manifest.icons).sort(([a], [b]) => a.localeCompare(b));
  const rows = [], lines = [];
  for (const [kit, lucide] of entries) {
    const file = path.join(DIR, `${lucide}.svg`);
    const buf = fs.readFileSync(file);
    lines.push(`  ${JSON.stringify(kit)}: ${JSON.stringify(parseSvg(buf.toString('utf8'), lucide))},`);
    rows.push(`| \`${kit}\` | \`${lucide}.svg\` | ${RAW(lucide)} | \`${sha(buf)}\` |`);
  }
  const data = `// GENERATED by tools/icons.mjs (Lucide ${manifest.version}, ISC) – do not edit by hand.
// kit name → shapes of a 24×24 symbol (stroke, currentColor); the source SVGs live under icons/.
export const LUCIDE_VERSION = ${JSON.stringify(manifest.version)};
export const ICONS = {
${lines.join('\n')}
};
`;
  const sources = `# Icons

[Lucide](https://github.com/lucide-icons/lucide) **${manifest.version}** (ISC licence, some icons MIT/Feather: \`LICENSE.txt\`). Only the used symbols
are in the repo. Fetch a new symbol: \`node tools/icons.mjs add <lucide-name> [--as <kit-name>]\` (uses the fixed version
\`${manifest.version}\`, lists it here and rebuilds \`js/icons-data.js\`). \`node tools/icons.mjs check\` verifies that both match
the files. \`logo.svg\` is the Tarn logo (own drawing, not Lucide).

| Kit name | File | Source | sha256 |
|---|---|---|---|
${rows.join('\n')}
`;
  return { 'js/icons-data.js': data, 'icons/SOURCES.md': sources };
}

function write(files) {
  for (const [rel, text] of Object.entries(files)) fs.writeFileSync(path.join(ROOT, rel), text);
}

async function fetchText(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return r.text();
}

async function main() {
  const [cmd, ...rest] = process.argv.slice(2);
  const fail = (msg, code = 2) => { console.log(`icons: ${msg}`); process.exit(code); };
  if (cmd === 'add') {
    const name = rest[0];
    if (!name || !/^[a-z0-9-]+$/.test(name)) fail('add <lucide-name> [--as <kit-name>]');
    const asIdx = rest.indexOf('--as');
    const kit = asIdx > 0 ? rest[asIdx + 1] : name;
    if (!kit || !/^[a-z0-9-]+$/.test(kit)) fail('invalid kit name');
    const m = readManifest();
    if (m.version !== LUCIDE_VERSION) fail(`manifest ${m.version} ≠ tool ${LUCIDE_VERSION}`);
    const svg = await fetchText(RAW(name)).catch((e) => fail(e.message));
    parseSvg(svg, name); // check before writing
    fs.mkdirSync(DIR, { recursive: true });
    fs.writeFileSync(path.join(DIR, `${name}.svg`), svg);
    if (!fs.existsSync(path.join(DIR, 'LICENSE.txt'))) fs.writeFileSync(path.join(DIR, 'LICENSE.txt'), await fetchText(RAW('', 'LICENSE')));
    m.icons[kit] = name;
    m.icons = Object.fromEntries(Object.entries(m.icons).sort(([a], [b]) => a.localeCompare(b)));
    fs.writeFileSync(MANIFEST, `${JSON.stringify(m, null, 2)}\n`);
    write(generate(m));
    console.log(`icons: ${kit} ← lucide ${name}@${LUCIDE_VERSION} added (icons/${name}.svg, js/icons-data.js, icons/SOURCES.md)`);
  } else if (cmd === 'build') {
    write(generate());
    console.log('icons: js/icons-data.js and icons/SOURCES.md generated');
  } else if (cmd === 'check') {
    const g = generate();
    const bad = Object.entries(g).filter(([rel, text]) => !fs.existsSync(path.join(ROOT, rel)) || fs.readFileSync(path.join(ROOT, rel), 'utf8') !== text).map(([rel]) => rel);
    console.log(bad.length ? `icons: ${bad.join(', ')} does not match icons/*.svg (node tools/icons.mjs build)` : `icons: ok (${Object.keys(readManifest().icons).length} symbols, Lucide ${LUCIDE_VERSION})`);
    process.exit(bad.length ? 1 : 0);
  } else if (cmd === 'list') {
    for (const [k, v] of Object.entries(readManifest().icons)) console.log(`${k}\t${v}`);
  } else fail('commands: add, build, check, list');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main().catch((e) => { console.log(`icons: ${e.message}`); process.exit(2); });
